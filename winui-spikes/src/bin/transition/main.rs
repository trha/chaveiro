//! Spike: do WinUI theme transitions play when a winui-immediate pass swaps
//! one screen for another?
//!
//! Four columns switch between screen A and screen B every two seconds:
//!
//! 1. A stack with `AddDeleteThemeTransition`, child keyed by screen.
//! 2. The same stack, child under one fixed id, so only its text changes.
//! 3. A `ContentPresenter` with `ContentThemeTransition`, content swapped.
//! 4. A plain stack, child keyed by screen, `EntranceThemeTransition` on it.
//! 5. A push: a clipped grid where the new screen slides in and the old one
//!    slides out the other side, both through `UIElement.Translation` with a
//!    `Vector3Transition`. A to B goes left, B to A goes right.
//!
//! Every 50 ms a tick runs a pass that logs how many visual children
//! columns 1 and 4 hold, to see how long a removed child stays drawn.
//!
//! `bindings.rs` is generated by windows-bindgen 0.100 in minimal flat mode
//! from the Windows App SDK 2.4 metadata, with the filter in `bindings.txt`.

// The program is Windows only. On other targets it is empty, so it checks
// but does not link.
#![cfg_attr(not(windows), no_main)]
#![cfg(windows)]

// Generated code: names follow WinRT, and the filter emits more than we call.
#[allow(nonstandard_style, dead_code, clippy::all)]
mod bindings;

use bindings::*;
use std::time::{Duration, Instant};
use windows_core::{IInspectable, Interface, Result};
use winui_immediate::{App, Orientation, Ui, run};

const TICK: Duration = Duration::from_millis(50);
const TICKS_PER_SWITCH: u32 = 40;
const SWITCHES: u32 = 6;

fn main() -> Result<()> {
    run(|| {
        Ok(Spike {
            screen: 0,
            ticks: 0,
            configured: false,
            presented: None,
            counts: (0, 0),
            started: Instant::now(),
            slide: Some(Slide::default()),
        })
    })
}

struct Spike {
    screen: u32,
    ticks: u32,
    /// Whether the transitions on the long-lived columns are set.
    configured: bool,
    /// The screen the presenter in column 3 shows.
    presented: Option<u32>,
    /// Visual child counts of columns 1 and 4 at the last log line.
    counts: (i32, i32),
    started: Instant,
    /// Column 5. Taken out for the pass, because the native closure borrows
    /// it while `self` is borrowed for the name.
    slide: Option<Slide>,
}

/// Column 5's screens: the one shown, and those still sliding out.
#[derive(Default)]
struct Slide {
    shown: Option<u32>,
    current: Option<UIElement>,
    /// Each with the time after which it leaves the grid.
    leaving: Vec<(UIElement, Instant)>,
    count: u32,
}

const PUSH_WIDTH: f32 = 260.0;
const PUSH_DURATION: Duration = Duration::from_millis(250);
/// How long a leaving screen stays in the grid: the slide plus a margin.
const PUSH_REMOVE_AFTER: Duration = Duration::from_millis(350);

/// Runs on every pass: drops leaving screens whose slide is over, and on a
/// new screen starts both slides.
fn push(element: &IInspectable, slide: &mut Slide, screen: u32, name: &str) -> Result<()> {
    let children = element
        .cast::<Panel>()?
        .Children()?
        .cast::<windows_collections::IVector<UIElement>>()?;
    let now = Instant::now();
    let mut kept = Vec::new();
    for (leaving, deadline) in slide.leaving.drain(..) {
        if now < deadline {
            kept.push((leaving, deadline));
            continue;
        }
        let mut index = 0;
        if children.IndexOf(&leaving, &mut index)? {
            children.RemoveAt(index)?;
        }
    }
    slide.leaving = kept;

    if slide.shown != Some(screen) {
        let block = TextBlock::new()?;
        block.SetText(name)?;
        big(block.clone())?;
        let entering = block.cast::<UIElement>()?;
        match slide.current.take() {
            None => children.Append(&entering)?,
            Some(old) => {
                // Odd screens come after even ones: forward, so the new
                // screen enters from the right.
                let sign = if screen % 2 == 1 { 1.0 } else { -1.0 };
                entering.SetTranslation(offset(sign * PUSH_WIDTH))?;
                children.Append(&entering)?;
                entering.SetTranslationTransition(&transition()?)?;
                entering.SetTranslation(offset(0.0))?;
                old.SetTranslationTransition(&transition()?)?;
                old.SetTranslation(offset(-sign * PUSH_WIDTH))?;
                slide.leaving.push((old, now + PUSH_REMOVE_AFTER));
            }
        }
        slide.current = Some(entering);
        slide.shown = Some(screen);
    }
    let count = children.Size()?;
    if count != slide.count {
        eprintln!("push grid children: {count}");
        slide.count = count;
    }
    Ok(())
}

fn offset(x: f32) -> windows_numerics::Vector3 {
    windows_numerics::Vector3 { x, y: 0.0, z: 0.0 }
}

fn transition() -> Result<Vector3Transition> {
    let transition = Vector3Transition::new()?;
    transition.SetDuration(
        windows_time::TimeSpan::try_from(PUSH_DURATION).expect("250 ms fits a TimeSpan"),
    )?;
    Ok(transition)
}

impl App for Spike {
    fn view(&mut self, ui: &mut Ui) -> Result<()> {
        let mut ticks = ui.stream("tick", || winui_executor::interval(TICK));
        while ticks.next().is_some() {
            self.ticks += 1;
            if self.ticks % TICKS_PER_SWITCH == 0 {
                self.screen += 1;
                eprintln!("{:>6} ms switch to screen {}", self.elapsed(), self.name());
            }
        }
        if self.screen >= SWITCHES {
            return Ok(());
        }
        let screen = self.screen;
        let name = self.name();
        let configure = !self.configured;
        let mut keyed_panel = None;
        let mut entrance_panel = None;
        let mut presented = self.presented;
        let mut slide = self.slide.take();
        ui.window("main", "transition spike", |ui| {
            ui.stack("columns", Orientation::Horizontal, 48.0, |ui| {
                let keyed = ui.stack("keyed", Orientation::Vertical, 0.0, |ui| {
                    big(ui
                        .label(("screen", screen), format_args!("{name}"))?
                        .cast()?)
                })?;
                if configure {
                    keyed.cast::<Panel>()?.SetChildrenTransitions(&collection(
                        AddDeleteThemeTransition::new()?.cast()?,
                    )?)?;
                }
                keyed_panel = Some(keyed.element());

                let fixed = ui.stack("fixed", Orientation::Vertical, 0.0, |ui| {
                    big(ui.label("screen", format_args!("{name}"))?.cast()?)
                })?;
                if configure {
                    fixed.cast::<Panel>()?.SetChildrenTransitions(&collection(
                        AddDeleteThemeTransition::new()?.cast()?,
                    )?)?;
                }

                ui.native(
                    "presenter",
                    || {
                        let presenter = ContentPresenter::new()?;
                        let transition = ContentThemeTransition::new()?;
                        transition.SetHorizontalOffset(120.0)?;
                        presenter.SetContentTransitions(&collection(transition.cast()?)?)?;
                        presenter.cast()
                    },
                    |element| {
                        if presented != Some(screen) {
                            let block = TextBlock::new()?;
                            block.SetText(name)?;
                            big(block.clone())?;
                            element.cast::<ContentPresenter>()?.SetContent(&block)?;
                            presented = Some(screen);
                        }
                        Ok(())
                    },
                )?;

                let entrance = ui.stack("entrance", Orientation::Vertical, 0.0, |ui| {
                    let label = ui.label(("screen", screen), format_args!("{name}"))?;
                    let block = label.cast::<TextBlock>()?;
                    big(block.clone())?;
                    // The keyed label is new on the pass after a switch; setting
                    // the collection again on later passes is harmless here.
                    block
                        .cast::<UIElement>()?
                        .SetTransitions(&collection(EntranceThemeTransition::new()?.cast()?)?)?;
                    Ok(())
                })?;
                entrance_panel = Some(entrance.element());

                ui.native(
                    "push",
                    || {
                        let grid = Grid::new()?;
                        let frame = grid.cast::<FrameworkElement>()?;
                        frame.SetWidth(PUSH_WIDTH as f64)?;
                        frame.SetHeight(60.0)?;
                        let clip = RectangleGeometry::new()?;
                        clip.SetRect(Rect {
                            x: 0.0,
                            y: 0.0,
                            width: PUSH_WIDTH,
                            height: 60.0,
                        })?;
                        grid.cast::<UIElement>()?.SetClip(&clip)?;
                        grid.cast()
                    },
                    |element| {
                        push(
                            element,
                            slide.as_mut().expect("set before the pass"),
                            screen,
                            name,
                        )
                    },
                )?;
                Ok(())
            })?;
            Ok(())
        })?;
        self.configured = true;
        self.presented = presented;
        self.slide = slide;
        let counts = (
            visual_children(keyed_panel.as_ref())?,
            visual_children(entrance_panel.as_ref())?,
        );
        if counts != self.counts {
            eprintln!(
                "{:>6} ms visual children: keyed+AddDelete {}, keyed+Entrance {}",
                self.elapsed(),
                counts.0,
                counts.1
            );
            self.counts = counts;
        }
        Ok(())
    }
}

impl Spike {
    fn name(&self) -> &'static str {
        if self.screen % 2 == 0 {
            "Screen A"
        } else {
            "Screen B"
        }
    }

    fn elapsed(&self) -> u128 {
        self.started.elapsed().as_millis()
    }
}

fn big(block: TextBlock) -> Result<()> {
    block.SetFontSize(40.0)
}

fn collection(transition: Transition) -> Result<TransitionCollection> {
    let collection = TransitionCollection::new()?;
    collection
        .cast::<windows_collections::IVector<Transition>>()?
        .Append(&transition)?;
    Ok(collection)
}

fn visual_children(element: Option<&IInspectable>) -> Result<i32> {
    let element = element.expect("the pass declared the column");
    VisualTreeHelper::GetChildrenCount(&element.cast::<DependencyObject>()?)
}
