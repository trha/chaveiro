//! Spike: can one container morph between any two elements, with a real
//! Gaussian blur on their rendered pixels?
//!
//! Rows are content kinds (an icon, a text, a panel with both). Columns are
//! ways to morph between content A and content B, every 1.5 s:
//!
//! 1. `fade`: XAML only. Each child has an `OpacityTransition` and a
//!    `ScaleTransition`, and the pass flips `Opacity` and `Scale`.
//! 2. `blur, hide XAML`: each child is drawn by a `SpriteVisual` whose brush
//!    is a Gaussian blur over a `CompositionVisualSurface` of the child. The
//!    real child is hidden with `UIElement.Opacity = 0`.
//! 3. `blur, hide visual`: the same, but the child is hidden through the
//!    opacity of its own composition visual, the one the surface reads.
//! 4. `blur, hide wrapper`: each child sits in a `Border`. The border is
//!    hidden with `UIElement.Opacity = 0` and the surface reads the child.
//!
//! The blur effect is a hand-written `IGraphicsEffect` that names the D2D
//! Gaussian blur, so Win2D is not needed.
//!
//! `MORPH_FREEZE=<amount>` stops the switching and holds the shown sprite at
//! that blur amount, so a screenshot shows whether each column blurs and
//! whether its hidden source still draws into the surface.
//! `MORPH_MS=<ms>` sets the morph length, 300 ms by default.
//!
//! `bindings.rs` is generated by `tools/winui-bindgen` from the Windows App
//! SDK 2.7 metadata, with the filter in `bindings.txt`.

// The program is Windows only. On other targets it is empty, so it checks
// but does not link.
#![cfg_attr(not(windows), no_main)]
#![cfg(windows)]

// Generated code: names follow WinRT, and the filter emits more than we call.
#[allow(nonstandard_style, dead_code, clippy::all)]
mod bindings;

use bindings::*;
use std::{cell::RefCell, ffi::c_void, time::Duration};
use windows_core::{
    GUID, HSTRING, IInspectable, Interface, PCWSTR, Result, implement_decl, interface_decl,
};
use windows_numerics::{Vector2, Vector3};
use winui_immediate::{App, Orientation as StackOrientation, Ui, run};

const TICK: Duration = Duration::from_millis(50);
const TICKS_PER_SWITCH: u32 = 30;
/// Blur amount of a sprite that is fully out.
const BLUR_OUT: f32 = 8.0;
/// Room around the source for the blur to spread into, in pixels.
const PAD: f32 = 16.0;
const COPY: &str = "\u{E8C8}";
const CHECK_MARK: &str = "\u{E73E}";

fn main() -> Result<()> {
    let freeze = std::env::var("MORPH_FREEZE")
        .ok()
        .map(|text| text.parse::<f32>().expect("MORPH_FREEZE is a number"));
    let length = std::env::var("MORPH_MS").ok().map_or(300, |text| {
        text.parse::<u64>().expect("MORPH_MS is a whole number")
    });
    run(move || {
        let cells = [Kind::Icon, Kind::Text, Kind::Panel]
            .into_iter()
            .flat_map(|kind| {
                [
                    Method::Fade,
                    Method::HideXaml,
                    Method::HideVisual,
                    Method::HideWrapper,
                ]
                .map(|method| Cell {
                    kind,
                    method,
                    parts: None,
                    sprites: None,
                    failed: false,
                    shown: 0,
                })
            })
            .collect();
        Ok(Spike {
            ticks: 0,
            shown: 0,
            freeze,
            length: Duration::from_millis(length),
            cells: Some(cells),
        })
    })
}

struct Spike {
    ticks: u32,
    /// Which content every cell should show: 0 for A, 1 for B.
    shown: usize,
    freeze: Option<f32>,
    length: Duration,
    /// Taken out for the pass, because the native closures borrow cells
    /// while `ui` is borrowed.
    cells: Option<Vec<Cell>>,
}

#[derive(Clone, Copy, Debug)]
enum Kind {
    Icon,
    Text,
    Panel,
}

#[derive(Clone, Copy, Debug, PartialEq)]
enum Method {
    Fade,
    HideXaml,
    HideVisual,
    HideWrapper,
}

struct Cell {
    kind: Kind,
    method: Method,
    parts: Option<Parts>,
    /// Set once both children have a size.
    sprites: Option<[Sprite; 2]>,
    /// Whether the composition setup failed; the cell then shows plain XAML.
    failed: bool,
    /// What the cell shows now.
    shown: usize,
}

struct Parts {
    grid: Grid,
    /// The grid's children: the contents, or for `HideWrapper` their borders.
    slots: [UIElement; 2],
    contents: [UIElement; 2],
}

struct Sprite {
    visual: SpriteVisual,
    brush: CompositionEffectBrush,
}

impl App for Spike {
    fn view(&mut self, ui: &mut Ui) -> Result<()> {
        let mut ticks = ui.stream("tick", || winui_executor::interval(TICK));
        while ticks.next().is_some() {
            self.ticks += 1;
            if self.freeze.is_none() && self.ticks % TICKS_PER_SWITCH == 0 {
                self.shown = 1 - self.shown;
            }
        }
        let shown = self.shown;
        let freeze = self.freeze;
        let length = self.length;
        let mut cells = self.cells.take().expect("put back after each pass");
        let result = ui.window("main", "morph spike", |ui| {
            ui.stack("rows", StackOrientation::Vertical, 16.0, |ui| {
                ui.stack("header", StackOrientation::Horizontal, 0.0, |ui| {
                    for (index, name) in [
                        "",
                        "fade",
                        "blur, hide XAML",
                        "blur, hide visual",
                        "blur, hide wrapper",
                    ]
                    .into_iter()
                    .enumerate()
                    {
                        ui.label(index, format_args!("{name}"))?
                            .cast::<FrameworkElement>()?
                            .SetWidth(160.0)?;
                    }
                    Ok(())
                })?;
                for (row, chunk) in cells.chunks_mut(4).enumerate() {
                    ui.stack(("row", row), StackOrientation::Horizontal, 0.0, |ui| {
                        ui.label("kind", format_args!("{:?}", chunk[0].kind))?
                            .cast::<FrameworkElement>()?
                            .SetWidth(160.0)?;
                        for (column, cell) in chunk.iter_mut().enumerate() {
                            let mut created = None;
                            ui.native(column, |_: &winui_immediate::NativeSender<()>| {
                                let (element, parts) = create(cell.kind, cell.method)?;
                                created = Some(parts);
                                Ok((element, ()))
                            })?;
                            if created.is_some() {
                                cell.parts = created;
                            }
                            cell.update(shown, freeze, length);
                        }
                        Ok(())
                    })?;
                }
                Ok(())
            })?;
            Ok(())
        });
        self.cells = Some(cells);
        result.map(|_| ())
    }
}

/// A cell's grid, with content A shown and B hidden.
fn create(kind: Kind, method: Method) -> Result<(IInspectable, Parts)> {
    let grid = Grid::new()?;
    let frame = grid.cast::<FrameworkElement>()?;
    frame.SetWidth(160.0)?;
    frame.SetHeight(56.0)?;
    let children = grid.cast::<Panel>()?.Children()?;
    let contents = [content(kind, 0)?, content(kind, 1)?];
    let slots = if method == Method::HideWrapper {
        let wrap = |content: &UIElement| -> Result<UIElement> {
            let border = Border::new()?;
            border.SetChild(content)?;
            center(&border.cast()?)?;
            border.cast()
        };
        [wrap(&contents[0])?, wrap(&contents[1])?]
    } else {
        contents.clone()
    };
    for slot in &slots {
        children
            .cast::<windows_collections::IVector<UIElement>>()?
            .Append(slot)?;
    }
    if method == Method::Fade {
        for content in &contents {
            content.SetOpacityTransition(&scalar_transition()?)?;
            content.SetScaleTransition(&vector_transition()?)?;
        }
    }
    // B starts out of view in every method.
    contents[1].SetOpacity(0.0)?;
    Ok((
        grid.cast()?,
        Parts {
            grid,
            slots,
            contents,
        },
    ))
}

impl Cell {
    /// Runs on every pass. Logs and gives up the blur on a setup error, so
    /// one failing column does not end the spike.
    fn update(&mut self, shown: usize, freeze: Option<f32>, length: Duration) {
        if let Err(error) = self.try_update(shown, freeze, length) {
            eprintln!("{:?} {:?}: {error}", self.kind, self.method);
            self.failed = true;
        }
    }

    fn try_update(&mut self, shown: usize, freeze: Option<f32>, length: Duration) -> Result<()> {
        let parts = self.parts.as_ref().expect("create ran first");
        if self.method == Method::Fade {
            if parts.contents[0].ActualSize()?.x > 0.0 {
                for content in &parts.contents {
                    let size = content.ActualSize()?;
                    content.SetCenterPoint(Vector3 {
                        x: size.x / 2.0,
                        y: size.y / 2.0,
                        z: 0.0,
                    })?;
                }
            }
            if shown != self.shown {
                fade(&parts.contents[self.shown], false)?;
                fade(&parts.contents[shown], true)?;
                self.shown = shown;
            }
            return Ok(());
        }
        if self.failed {
            return Ok(());
        }
        if self.sprites.is_none() {
            let sizes = [
                parts.contents[0].ActualSize()?,
                parts.contents[1].ActualSize()?,
            ];
            if sizes.iter().any(|size| size.x == 0.0) {
                return Ok(());
            }
            self.sprites = Some(self.set_up(freeze)?);
            eprintln!(
                "{:?} {:?}: sprites set up, sizes {sizes:?}",
                self.kind, self.method
            );
            return Ok(());
        }
        if shown != self.shown {
            let sprites = self.sprites.as_ref().expect("checked above");
            animate(&sprites[self.shown], false, length)?;
            animate(&sprites[shown], true, length)?;
            self.shown = shown;
        }
        Ok(())
    }

    fn set_up(&self, freeze: Option<f32>) -> Result<[Sprite; 2]> {
        let parts = self.parts.as_ref().expect("create ran first");
        let compositor = ElementCompositionPreview::GetElementVisual(&parts.grid)?
            .cast::<CompositionObject>()?
            .Compositor()?;
        let container = compositor.CreateContainerVisual()?;
        let sprite = |index: usize| -> Result<Sprite> {
            let content = &parts.contents[index];
            let size = content.ActualSize()?;
            let offset = parts.slots[index].ActualOffset()?;
            let source = ElementCompositionPreview::GetElementVisual(content)?;
            let surface = compositor
                .cast::<ICompositorWithVisualSurface>()?
                .CreateVisualSurface()?;
            surface.SetSourceVisual(&source)?;
            surface.SetSourceOffset(Vector2 { x: -PAD, y: -PAD })?;
            let padded = Vector2 {
                x: size.x + 2.0 * PAD,
                y: size.y + 2.0 * PAD,
            };
            surface.SetSourceSize(padded)?;
            let surface_brush = compositor
                .CreateSurfaceBrushWithSurface(&surface.cast::<ICompositionSurface>()?)?;
            let effect: IGraphicsEffect = BlurEffect {
                name: RefCell::new(HSTRING::from("Blur")),
                source: CompositionEffectSourceParameter::Create("source")?.cast()?,
            }
            .into();
            let factory = compositor.CreateEffectFactoryWithProperties(
                &effect,
                &windows_collections::IIterable::<HSTRING>::from(vec![HSTRING::from(
                    "Blur.BlurAmount",
                )]),
            )?;
            let brush = factory.CreateBrush()?;
            brush.SetSourceParameter("source", &surface_brush.cast::<CompositionBrush>()?)?;
            let visual = compositor.CreateSpriteVisual()?;
            visual.SetBrush(&brush.cast::<CompositionBrush>()?)?;
            let as_visual = visual.cast::<Visual>()?;
            as_visual.SetSize(padded)?;
            as_visual.SetOffset(Vector3 {
                x: offset.x - PAD,
                y: offset.y - PAD,
                z: 0.0,
            })?;
            let shown = index == self.shown;
            as_visual.SetOpacity(if shown { 1.0 } else { 0.0 })?;
            brush
                .cast::<CompositionObject>()?
                .Properties()?
                .InsertScalar(
                    "Blur.BlurAmount",
                    if shown {
                        freeze.unwrap_or(0.0)
                    } else {
                        BLUR_OUT
                    },
                )?;
            container.Children()?.InsertAtTop(&as_visual)?;
            // Hide the real element now that its sprite draws it. Content B
            // was created hidden, so undo that first.
            parts.contents[index].SetOpacity(1.0)?;
            match self.method {
                Method::HideXaml | Method::HideWrapper => parts.slots[index].SetOpacity(0.0)?,
                Method::HideVisual => source.SetOpacity(0.0)?,
                Method::Fade => unreachable!("fade has no sprites"),
            }
            Ok(Sprite { visual, brush })
        };
        let sprites = [sprite(0)?, sprite(1)?];
        ElementCompositionPreview::SetElementChildVisual(
            &parts.grid,
            &container.cast::<Visual>()?,
        )?;
        Ok(sprites)
    }
}

/// Content A (`index` 0, the copy state) or B (1, the done state).
fn content(kind: Kind, index: usize) -> Result<UIElement> {
    let glyph = [COPY, CHECK_MARK][index];
    let text = ["Copy", "Copied"][index];
    let icon = || -> Result<UIElement> {
        let icon = FontIcon::new()?;
        icon.SetGlyph(glyph)?;
        icon.SetFontSize(20.0)?;
        icon.cast()
    };
    let label = || -> Result<UIElement> {
        let block = TextBlock::new()?;
        block.SetText(text)?;
        block.SetFontSize(20.0)?;
        block.cast()
    };
    let element = match kind {
        Kind::Icon => icon()?,
        Kind::Text => label()?,
        Kind::Panel => {
            let stack = StackPanel::new()?;
            stack.SetOrientation(Orientation::Horizontal)?;
            stack.SetSpacing(6.0)?;
            let children = stack
                .cast::<Panel>()?
                .Children()?
                .cast::<windows_collections::IVector<UIElement>>()?;
            children.Append(&icon()?)?;
            children.Append(&label()?)?;
            stack.cast()?
        }
    };
    center(&element.cast()?)?;
    Ok(element)
}

fn center(element: &FrameworkElement) -> Result<()> {
    element.SetHorizontalAlignment(HorizontalAlignment::Center)?;
    element.SetVerticalAlignment(VerticalAlignment::Center)
}

fn fade(content: &UIElement, show: bool) -> Result<()> {
    content.SetOpacity(if show { 1.0 } else { 0.0 })?;
    let scale = if show { 1.0 } else { 0.6 };
    content.SetScale(Vector3 {
        x: scale,
        y: scale,
        z: 1.0,
    })
}

fn animate(sprite: &Sprite, show: bool, length: Duration) -> Result<()> {
    let compositor = sprite.visual.cast::<CompositionObject>()?.Compositor()?;
    let keyframes = |from: f32, to: f32| -> Result<CompositionAnimation> {
        let animation = compositor.CreateScalarKeyFrameAnimation()?;
        animation.InsertKeyFrame(0.0, from)?;
        animation.InsertKeyFrame(1.0, to)?;
        animation
            .cast::<KeyFrameAnimation>()?
            .SetDuration(time_span(length))?;
        animation.cast()
    };
    let (opacity, blur) = if show {
        ((0.0, 1.0), (BLUR_OUT, 0.0))
    } else {
        ((1.0, 0.0), (0.0, BLUR_OUT))
    };
    sprite
        .visual
        .cast::<CompositionObject>()?
        .StartAnimation("Opacity", &keyframes(opacity.0, opacity.1)?)?;
    sprite
        .brush
        .cast::<CompositionObject>()?
        .StartAnimation("Blur.BlurAmount", &keyframes(blur.0, blur.1)?)
}

fn time_span(length: Duration) -> windows_time::TimeSpan {
    windows_time::TimeSpan::try_from(length).expect("a morph length fits a TimeSpan")
}

fn scalar_transition() -> Result<ScalarTransition> {
    let transition = ScalarTransition::new()?;
    transition.SetDuration(time_span(Duration::from_millis(300)))?;
    Ok(transition)
}

fn vector_transition() -> Result<Vector3Transition> {
    let transition = Vector3Transition::new()?;
    transition.SetDuration(time_span(Duration::from_millis(300)))?;
    Ok(transition)
}

// From windows.graphics.effects.interop.h. Composition reads an effect
// description through this interface.
interface_decl! {
    unsafe trait IGraphicsEffectD2D1Interop(IGraphicsEffectD2D1Interop_Vtbl, IGraphicsEffectD2D1Interop_Impl): windows_core::IUnknown
        = 0x2fc57384_a068_44d7_a331_30982fcf7177
    {
        unsafe fn GetEffectId(&self, id: *mut GUID) -> Result<()>;
        unsafe fn GetNamedPropertyMapping(&self, name: PCWSTR, index: *mut u32, mapping: *mut i32) -> Result<()>;
        unsafe fn GetPropertyCount(&self, count: *mut u32) -> Result<()>;
        unsafe fn GetProperty(&self, index: u32, value: *mut *mut c_void) -> Result<()>;
        unsafe fn GetSource(&self, index: u32, source: *mut *mut c_void) -> Result<()>;
        unsafe fn GetSourceCount(&self, count: *mut u32) -> Result<()>;
    }
}

const CLSID_D2D1_GAUSSIAN_BLUR: GUID = GUID::from_u128(0x1feb6d69_2fe6_4ac9_8c58_1d7f93e7a6a5);
/// `GRAPHICS_EFFECT_PROPERTY_MAPPING_DIRECT`: the value goes to D2D as is.
const MAPPING_DIRECT: i32 = 1;
/// D2D1_GAUSSIANBLUR_PROP_*: standard deviation (f32), optimization (u32),
/// border mode (u32).
const PROPERTY_NAMES: [&str; 3] = ["BlurAmount", "Optimization", "BorderMode"];
const E_INVALIDARG: windows_core::HRESULT = windows_core::HRESULT(0x8007_0057_u32 as i32);
const E_BOUNDS: windows_core::HRESULT = windows_core::HRESULT(0x8000_000B_u32 as i32);

/// A D2D Gaussian blur of one source. Its only animatable property is
/// `BlurAmount`; the brush starts it at 0.
struct BlurEffect {
    name: RefCell<HSTRING>,
    source: IGraphicsEffectSource,
}

implement_decl! {
    impl BlurEffect as BlurEffect_Impl: [IGraphicsEffect, IGraphicsEffectSource, IGraphicsEffectD2D1Interop]
}

impl IGraphicsEffectSource_Impl for BlurEffect_Impl {}

impl IGraphicsEffect_Impl for BlurEffect_Impl {
    fn Name(&self) -> Result<HSTRING> {
        Ok(self.name.borrow().clone())
    }

    fn SetName(&self, value: &HSTRING) -> Result<()> {
        *self.name.borrow_mut() = value.clone();
        Ok(())
    }
}

impl IGraphicsEffectD2D1Interop_Impl for BlurEffect_Impl {
    unsafe fn GetEffectId(&self, id: *mut GUID) -> Result<()> {
        unsafe { *id = CLSID_D2D1_GAUSSIAN_BLUR };
        Ok(())
    }

    unsafe fn GetNamedPropertyMapping(
        &self,
        name: PCWSTR,
        index: *mut u32,
        mapping: *mut i32,
    ) -> Result<()> {
        let name =
            unsafe { name.to_string() }.map_err(|_| windows_core::Error::from(E_INVALIDARG))?;
        let position = PROPERTY_NAMES
            .iter()
            .position(|known| known.eq_ignore_ascii_case(&name))
            .ok_or_else(|| windows_core::Error::from(E_INVALIDARG))?;
        unsafe {
            *index = u32::try_from(position).expect("three properties");
            *mapping = MAPPING_DIRECT;
        }
        Ok(())
    }

    unsafe fn GetPropertyCount(&self, count: *mut u32) -> Result<()> {
        unsafe { *count = 3 };
        Ok(())
    }

    unsafe fn GetProperty(&self, index: u32, value: *mut *mut c_void) -> Result<()> {
        let boxed: IInspectable = match index {
            0 => windows_reference::IReference::<f32>::from(0.0).into(),
            // D2D1_GAUSSIANBLUR_OPTIMIZATION_BALANCED.
            1 => windows_reference::IReference::<u32>::from(1).into(),
            // D2D1_BORDER_MODE_SOFT: the blur fades out past the edges.
            2 => windows_reference::IReference::<u32>::from(0).into(),
            _ => return Err(E_BOUNDS.into()),
        };
        let property = boxed.cast::<IPropertyValue>()?;
        unsafe { *value = property.into_raw() };
        Ok(())
    }

    unsafe fn GetSource(&self, index: u32, source: *mut *mut c_void) -> Result<()> {
        if index != 0 {
            return Err(E_BOUNDS.into());
        }
        unsafe { *source = self.source.clone().into_raw() };
        Ok(())
    }

    unsafe fn GetSourceCount(&self, count: *mut u32) -> Result<()> {
        unsafe { *count = 1 };
        Ok(())
    }
}
