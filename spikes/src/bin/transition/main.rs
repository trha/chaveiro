//! Spike: do WinUI theme transitions play when a winui-immediate pass swaps
//! one screen for another?
//!
//! Four columns switch between screen A and screen B every two seconds:
//!
//! 1. A stack with `AddDeleteThemeTransition`, child keyed by screen.
//! 2. The same stack, child under one fixed id, so only its text changes.
//! 3. A `ContentPresenter` with `ContentThemeTransition`, content swapped.
//! 4. A plain stack, child keyed by screen, `EntranceThemeTransition` on it.
//!
//! Every 50 ms a tick runs a pass that logs how many visual children
//! columns 1 and 4 hold, to see how long a removed child stays drawn.
//!
//! `bindings.rs` is generated by windows-bindgen 0.100 in minimal flat mode
//! from the Windows App SDK 2.4 metadata, with the filter in `bindings.txt`.

// Generated code: names follow WinRT, and the filter emits more than we call.
#[allow(nonstandard_style, dead_code, clippy::all)]
mod bindings;

use bindings::*;
use std::time::{Duration, Instant};
use windows_core::{IInspectable, Interface, Result};
use winui_immediate::{App, Handle, Orientation, Ui, run};

const TICK: Duration = Duration::from_millis(50);
const TICKS_PER_SWITCH: u32 = 40;
const SWITCHES: u32 = 6;

fn main() -> Result<()> {
    run(|handle: Handle<()>| {
        std::thread::spawn(move || {
            // The loop ends when the window is gone and send fails.
            while handle.send(()) {
                std::thread::sleep(TICK);
            }
        });
        Ok(Spike {
            screen: 0,
            ticks: 0,
            configured: false,
            presented: None,
            counts: (0, 0),
            started: Instant::now(),
        })
    })
}

struct Spike {
    screen: u32,
    ticks: u32,
    /// Whether the transitions on the long-lived columns are set.
    configured: bool,
    /// The screen the presenter in column 3 shows.
    presented: Option<u32>,
    /// Visual child counts of columns 1 and 4 at the last log line.
    counts: (i32, i32),
    started: Instant,
}

impl App for Spike {
    type Message = ();

    fn update(&mut self, (): ()) {
        self.ticks += 1;
        if self.ticks % TICKS_PER_SWITCH == 0 {
            self.screen += 1;
            eprintln!("{:>6} ms switch to screen {}", self.elapsed(), self.name());
        }
    }

    fn view(&mut self, ui: &mut Ui) -> Result<()> {
        if self.screen >= SWITCHES {
            return Ok(());
        }
        let screen = self.screen;
        let name = self.name();
        let configure = !self.configured;
        let mut keyed_panel = None;
        let mut entrance_panel = None;
        let mut presented = self.presented;
        ui.window("main", "transition spike", |ui| {
            ui.stack("columns", Orientation::Horizontal, 48.0, |ui| {
                let keyed = ui.stack("keyed", Orientation::Vertical, 0.0, |ui| {
                    big(ui
                        .label(("screen", screen), format_args!("{name}"))?
                        .cast()?)
                })?;
                if configure {
                    keyed.cast::<Panel>()?.SetChildrenTransitions(&collection(
                        AddDeleteThemeTransition::new()?.cast()?,
                    )?)?;
                }
                keyed_panel = Some(keyed.element());

                let fixed = ui.stack("fixed", Orientation::Vertical, 0.0, |ui| {
                    big(ui.label("screen", format_args!("{name}"))?.cast()?)
                })?;
                if configure {
                    fixed.cast::<Panel>()?.SetChildrenTransitions(&collection(
                        AddDeleteThemeTransition::new()?.cast()?,
                    )?)?;
                }

                ui.native(
                    "presenter",
                    || {
                        let presenter = ContentPresenter::new()?;
                        let transition = ContentThemeTransition::new()?;
                        transition.SetHorizontalOffset(120.0)?;
                        presenter.SetContentTransitions(&collection(transition.cast()?)?)?;
                        presenter.cast()
                    },
                    |element| {
                        if presented != Some(screen) {
                            let block = TextBlock::new()?;
                            block.SetText(name)?;
                            big(block.clone())?;
                            element.cast::<ContentPresenter>()?.SetContent(&block)?;
                            presented = Some(screen);
                        }
                        Ok(())
                    },
                )?;

                let entrance = ui.stack("entrance", Orientation::Vertical, 0.0, |ui| {
                    let label = ui.label(("screen", screen), format_args!("{name}"))?;
                    let block = label.cast::<TextBlock>()?;
                    big(block.clone())?;
                    // The keyed label is new on the pass after a switch; setting
                    // the collection again on later passes is harmless here.
                    block
                        .cast::<UIElement>()?
                        .SetTransitions(&collection(EntranceThemeTransition::new()?.cast()?)?)?;
                    Ok(())
                })?;
                entrance_panel = Some(entrance.element());
                Ok(())
            })?;
            Ok(())
        })?;
        self.configured = true;
        self.presented = presented;
        let counts = (
            visual_children(keyed_panel.as_ref())?,
            visual_children(entrance_panel.as_ref())?,
        );
        if counts != self.counts {
            eprintln!(
                "{:>6} ms visual children: keyed+AddDelete {}, keyed+Entrance {}",
                self.elapsed(),
                counts.0,
                counts.1
            );
            self.counts = counts;
        }
        Ok(())
    }
}

impl Spike {
    fn name(&self) -> &'static str {
        if self.screen % 2 == 0 {
            "Screen A"
        } else {
            "Screen B"
        }
    }

    fn elapsed(&self) -> u128 {
        self.started.elapsed().as_millis()
    }
}

fn big(block: TextBlock) -> Result<()> {
    block.SetFontSize(40.0)
}

fn collection(transition: Transition) -> Result<TransitionCollection> {
    let collection = TransitionCollection::new()?;
    collection
        .cast::<windows_collections::IVector<Transition>>()?
        .Append(&transition)?;
    Ok(collection)
}

fn visual_children(element: Option<&IInspectable>) -> Result<i32> {
    let element = element.expect("the pass declared the column");
    VisualTreeHelper::GetChildrenCount(&element.cast::<DependencyObject>()?)
}
